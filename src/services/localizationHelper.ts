/**
 * Translates an activity definition dynamically based on active language
 */
export function getLocalizedActivity(activity: { id: string; name: string; description: string; cognitiveFunction: string; estimatedDuration: number; difficultyLevels: number[] }, lang: LanguageCode): LocalizedActivityInfo {
  const strings = getStrings(lang);
  const trans = ACTIVITY_TRANSLATIONS[activity.id];

  const name = (trans && trans.name[lang]) || (trans && trans.name.en) || activity.name;
  const description = (trans && trans.description[lang]) || (trans && trans.description.en) || activity.description;
  
  const cogFuncKey = activity.cognitiveFunction;
  const cogTrans = COGNITIVE_FUNCTIONS[cogFuncKey];
  const cognitiveFunction = (cogTrans && cogTrans[lang]) || (cogTrans && cogTrans.en) || activity.cognitiveFunction;

  const durationLabel = `${activity.estimatedDuration} ${strings.minuteShort || 'min'}`;
  const levelsLabel = `${strings.levels || 'Levels'} ${activity.difficultyLevels.join(', ')}`;

  return {
    name,
    description,
    cognitiveFunction,
    durationLabel,
    levelsLabel
  };
}

