/**
 * Translates a reminder item dynamically based on active language while keeping proper nouns
 */
export function getLocalizedReminder(reminder: Reminder, lang: LanguageCode): { title: string; detail: string } {
  const trans = REMINDER_DICTIONARY[reminder.title];
  if (!trans) {
    return { title: reminder.title, detail: reminder.detail };
  }

  const title = trans.title[lang] || trans.title.en || reminder.title;
  const detail = trans.detail[lang] || trans.detail.en || reminder.detail;

  return { title, detail };
}

/**
 * Translates a personal memory item dynamically based on active language while keeping proper nouns
 */
export function getLocalizedMemoryItem(item: PersonalMemoryItem, lang: LanguageCode): LocalizedMemoryItemInfo {
  // 1. Check direct lookup by item.id
  const byId = MEMORY_TRANSLATIONS[item.id];
  if (byId) {
    const name = (byId.name && (byId.name[lang] || byId.name.en)) || item.name;
    const relationshipOrDetail = (byId.rel && (byId.rel[lang] || byId.rel.en)) || item.relationshipOrDetail;
    const description = (byId.desc && (byId.desc[lang] || byId.desc.en)) || item.description;
    return { name, relationshipOrDetail, description };
  }

  // 2. Check lookup by relationshipOrDetail
  const byRel = MEMORY_TRANSLATIONS[item.relationshipOrDetail];
  if (byRel) {
    const name = (byRel.name && (byRel.name[lang] || byRel.name.en)) || item.name;
    const relationshipOrDetail = (byRel.rel && (byRel.rel[lang] || byRel.rel.en)) || item.relationshipOrDetail;
    const description = (byRel.desc && (byRel.desc[lang] || byRel.desc.en)) || item.description;
    return { name, relationshipOrDetail, description };
  }

  // 3. Check lookup by name
  const byName = MEMORY_TRANSLATIONS[item.name];
  if (byName) {
    const name = (byName.name && (byName.name[lang] || byName.name.en)) || item.name;
    const relationshipOrDetail = (byName.rel && (byName.rel[lang] || byName.rel.en)) || item.relationshipOrDetail;
    const description = (byName.desc && (byName.desc[lang] || byName.desc.en)) || item.description;
    return { name, relationshipOrDetail, description };
  }

  return {
    name: item.name,
    relationshipOrDetail: item.relationshipOrDetail,
    description: item.description
  };
}

